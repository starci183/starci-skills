async function loadOperators() {
  const entries = await readdir(path.join(root, 'operators'), { withFileTypes: true });
  const dirs = entries.filter((e) => e.isDirectory()).map((e) => e.name).sort();
  const ops = [];
  for (const dir of dirs) {
    const manifest = await readJson(`operators/${dir}/operator.json`);
    ops.push({
      dir,
      id: manifest.id,
      manifest,
      en: await read(`operators/${dir}/operator.md`),
      vi: await read(`operators/${dir}/operator.vi.md`).catch(() => null),
    });
  }
  return ops.sort((a, b) => a.id.localeCompare(b.id));
}

async function loadWorkflows() {
  const files = (await readdir(path.join(root, 'workflows'))).filter((f) => f.endsWith('.json')).sort();
  return Promise.all(files.map(async (f) => readJson(`workflows/${f}`)));
}

async function loadKinds() {
  const files = (await readdir(path.join(root, 'templates/kinds'))).sort();
  const contracts = [];
  const schemas = [];
  for (const f of files) {
    if (f === 'contract.schema.json') continue;
    if (f.endsWith('.contract.json')) contracts.push(await readJson(`templates/kinds/${f}`));
    else if (f.endsWith('.schema.json')) schemas.push({ file: f, json: await readJson(`templates/kinds/${f}`) });
  }
  return { contracts, schemas, skeletons: files.filter((f) => f.endsWith('.skeleton.md')) };
}

