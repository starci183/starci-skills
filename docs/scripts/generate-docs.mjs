async function listExisting(rel) {
  const abs = path.join(docsRoot, rel);
  const out = [];
  const walk = async (dir) => {
    let entries;
    try { entries = await readdir(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) await walk(full);
      else out.push(path.relative(docsRoot, full).split(path.sep).join('/'));
    }
  };
  await walk(abs);
  return out;
}

const files = await render();
const roots = ['reference', 'vi/reference'];
const existing = (await Promise.all(roots.map(listExisting))).flat().sort();
const wanted = [...files.keys()].sort();

if (process.argv.includes('--check')) {
  const problems = [];
  for (const rel of wanted) {
    let current = null;
    try { current = await readFile(path.join(docsRoot, rel), 'utf8'); } catch { /* missing */ }
    if (current === null) problems.push(`missing: docs/${rel}`);
    else if (current.replace(/\r\n/g, '\n') !== files.get(rel)) problems.push(`stale:   docs/${rel}`);
  }
  for (const rel of existing) if (!files.has(rel)) problems.push(`extra:   docs/${rel}`);
  if (problems.length) {
    process.stderr.write(`docs are out of date with the tree (${problems.length}):\n${problems.join('\n')}\n`);
    process.stderr.write('run: node docs/scripts/generate-docs.mjs\n');
    process.exit(1);
  }
  process.stdout.write(`docs:check ok — ${wanted.length} generated files match the tree\n`);
} else {
  for (const rel of existing) if (!files.has(rel)) await rm(path.join(docsRoot, rel));
  for (const rel of wanted) {
    const abs = path.join(docsRoot, rel);
    await mkdir(path.dirname(abs), { recursive: true });
    await writeFile(abs, files.get(rel));
  }
  process.stdout.write(`docs: wrote ${wanted.length} generated files under docs/reference and docs/vi/reference\n`);
}
