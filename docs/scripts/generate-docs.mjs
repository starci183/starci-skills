const blob = (rel) => `${REPO}/blob/main/${rel.split(path.sep).join('/')}`;

// Line endings are normalised on the way in, so a CRLF file in the tree and its LF sibling generate
// byte-identical pages and `--check` cannot fail on invisible characters.
const read = async (rel) => (await readFile(path.join(root, rel), 'utf8')).replace(/\r\n/g, '\n');
const readJson = async (rel) => JSON.parse(await read(rel));

// ---------------------------------------------------------------------------
// MDX safety. Inline code and fenced code are not JSX in MDX, so only the text
// outside them can break the compiler: `<` opens a tag and `{` opens an
// expression. Escaping exactly those two characters, and only outside code,
// keeps every source line verbatim on screen.
// ---------------------------------------------------------------------------
function escapeOutsideCode(line) {
  let out = '';
  let rest = line;
  while (rest.length) {
    const tick = rest.indexOf('`');
    if (tick === -1) { out += esc(rest); break; }
    out += esc(rest.slice(0, tick));
    const close = rest.indexOf('`', tick + 1);
    if (close === -1) { out += rest.slice(tick); break; }
    out += rest.slice(tick, close + 1);
    rest = rest.slice(close + 1);
  }
  return out;
}
const esc = (s) => s.replace(/</g, '&lt;').replace(/\{/g, '&#123;');
// A cell that must hold a line break carries this sentinel through the escaper and becomes <br /> at
// the end, so the break is real markup while every other angle bracket stays literal text.
const BR = 'BR';

function mdx(text) {
  let fenced = false;
  return text.split('\n').map((line) => {
    if (/^\s*```/.test(line)) { fenced = !fenced; return line; }
    return fenced ? line : escapeOutsideCode(line);
  }).join('\n').split(BR).join('<br />');
}

// A copied file keeps its relative links; they are rewritten to the file they
// actually point at in the repository, because the docs site has no such path.
function relink(text, sourceRel) {
  const dir = path.posix.dirname(sourceRel.split(path.sep).join('/'));
  return text.replace(/\]\((?!https?:|#|\/)([^)]+)\)/g, (_m, target) => {
    const [file, hash = ''] = target.split('#');
    const resolved = path.posix.normalize(path.posix.join(dir, file));
    return `](${REPO}/blob/main/${resolved}${hash ? `#${hash}` : ''})`;
  });
}

const stripH1 = (text) => text.replace(/^#\s+.*\n+/, '');
const demote = (text) => {
  let fenced = false;
  return text.split('\n').map((line) => {
    if (/^\s*```/.test(line)) { fenced = !fenced; return line; }
    return !fenced && /^#{1,5} /.test(line) ? `#${line}` : line;
  }).join('\n');
};

function section(text, heading) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.trim() === heading);
  if (start === -1) throw new Error(`section "${heading}" not found`);
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i += 1) if (/^## /.test(lines[i])) { end = i; break; }
  return lines.slice(start + 1, end).join('\n').trim();
}

const front = (title, description) =>
  `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n`;
const generatedBy = (sources) =>
  `<Callout type="info">\nGenerated by \`docs/scripts/generate-docs.mjs\` from ${sources}. Edit the source, not this page.\n</Callout>\n`;
const callout = "import { Callout } from 'nextra/components'\n\n";

const tick = (s) => `\`${s}\``;
const cell = (v) => String(v).replace(/\|/g, '\\|');
const table = (header, rows) => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.join(' | ')} |`),
].join('\n');

