function operatorPage(op, lang) {
  const t = L[lang];
  const body = lang === 'en' ? op.en : op.vi;
  const rel = `operators/${op.dir}/operator.${lang === 'en' ? 'md' : 'vi.md'}`;
  const r = op.manifest.resources ?? {};
  const p = r.policy ?? {};
  const binding = table(t.opBindingRows, [
    ['`id`', tick(op.manifest.id)],
    ['`domain`', tick(op.manifest.domain)],
    ['`resources.profile`', tick(r.profile ?? '—')],
    ['`resources.requires`', (r.requires ?? []).length ? r.requires.map(tick).join(', ') : '—'],
    ['`policy.webSearch`', tick(p.webSearch ?? '—')],
    ['`policy.grammarBound`', tick(String(p.grammarBound ?? '—'))],
    ['`policy.imageGeneration`', tick(p.imageGeneration ?? '—')],
  ]);
  return [
    front(op.manifest.id, op.manifest.job),
    callout,
    `# ${op.manifest.id}\n`,
    generatedBy(`[\`${rel}\`](${blob(rel)}) and [\`operators/${op.dir}/operator.json\`](${blob(`operators/${op.dir}/operator.json`)})`),
    `\n## ${t.opBinding}\n\n${binding}\n`,
    `\n${mdx(stripH1(body).trim())}\n`,
    `\n---\n\n${mdx(t.opSource(rel))}\n`,
  ].join('');
}

function operatorIndexPage(ops, lang) {
  const t = L[lang];
  const rows = ops.map((o) => [
    `[\`${o.id}\`](/reference/operators/${o.dir})`,
    tick(o.manifest.resources?.profile ?? '—'),
    tick(o.manifest.domain),
    cell(o.manifest.job),
  ]);
  return `${front(t.opIndexTitle, t.opIndexDesc)}# ${t.opIndexTitle}\n\n${mdx(t.opIndexIntro)}\n\n${table(t.opTable, rows)}\n`;
}

function presetOf(branch) {
  const req = branch.requirements;
  if (!req || !Object.keys(req).length) return '—';
  return Object.entries(req).map(([k, v]) => `\`${k}\` = \`${JSON.stringify(v)}\``).join(BR);
}

function workflowPage(wf, lang) {
  const t = L[lang];
  const rows = [];
  wf.chain.forEach((step, i) => {
    step.forEach((branch, j) => {
      rows.push([
        String(i + 1),
        `${i + 1}/${j + 1}`,
        `[\`${branch.operator}\`](/reference/operators/${branch.operator.replace(/\./g, '-')})`,
        presetOf(branch),
        branch.fanout ? tick(branch.fanout) : '—',
        branch.maxParallel ? String(branch.maxParallel) : '—',
      ]);
    });
  });
  const loops = (wf.loops ?? []).map((l) => [tick(l.from), tick(l.to), cell(l.when), String(l.maxRounds)]);
  const rel = `workflows/${wf.id}.json`;
  const parts = [
    front(wf.id, wf.when[lang] ?? wf.when.en),
    callout,
    `# ${wf.id}\n`,
    generatedBy(`[\`${rel}\`](${blob(rel)})`),
    `\n## ${t.wfWhen}\n\n> ${mdx(wf.when[lang] ?? wf.when.en)}\n`,
    `\n## ${t.wfChain}\n\n${mdx(table(t.wfChainTable, rows))}\n`,
    `\n## ${t.wfLoops}\n\n${loops.length ? mdx(table(t.wfLoopTable, loops)) : t.wfNoLoops}\n`,
    `\n## ${t.wfEnds}\n\n${tick(wf.ends)}\n`,
  ];
  return parts.join('');
}

function workflowIndexPage(wfs, lang) {
  const t = L[lang];
  const rows = wfs.map((w) => [
    `[\`${w.id}\`](/reference/workflows/${w.id})`,
    String(w.chain.length),
    tick(w.ends),
    cell(w.when[lang] ?? w.when.en),
  ]);
  return `${front(t.wfIndexTitle, t.wfIndexDesc)}# ${t.wfIndexTitle}\n\n${mdx(t.wfIndexIntro)}\n\n${mdx(table(t.wfTable, rows))}\n`;
}

function kindsPage(kinds, lang) {
  const t = L[lang];
  const out = [front(t.kindsTitle, t.kindsDesc), callout, `# ${t.kindsTitle}\n`,
    generatedBy(`[\`templates/kinds/\`](${REPO}/tree/main/templates/kinds)`),
    `\n${mdx(t.kindsIntro)}\n`, `\n## ${t.kindsContracts}\n`];
  for (const c of kinds.contracts) {
    const rows = (c.sections ?? []).map((s) => {
      const rowsNote = s.exactRows !== undefined ? `exactRows ${s.exactRows}`
        : s.minRows !== undefined ? `minRows ${s.minRows}`
          : s.rows ? s.rows.map(tick).join(', ') : '—';
      const cells = s.cell ? Object.entries(s.cell).map(([k, v]) => `${tick(k)}: \`${v}\``).join(BR) : '—';
      return [`\`${s.heading}\``, s.table ? `\`${cell(s.table)}\`` : '—', cell(rowsNote), cell(cells)];
    });
    out.push(`\n### ${tick(c.kind)}\n`);
    const meta = [`${t.kindsTitleRe}: \`${c.title}\``];
    const skeleton = `${c.kind}.skeleton.md`;
    if (kinds.skeletons.includes(skeleton)) meta.push(`${t.kindsSkeleton}: [\`templates/kinds/${skeleton}\`](${blob(`templates/kinds/${skeleton}`)})`);
    if (c.example) meta.push(`${t.kindsExample}: [\`${c.example}\`](${blob(c.example)})`);
    out.push(`\n${mdx(meta.join('  \n'))}\n`);
    out.push(`\n${mdx(table(t.kindsSectionTable, rows))}\n`);
  }
  out.push(`\n## ${t.kindsSchemas}\n`);
  const schemaRows = kinds.schemas.map((s) => [
    tick(s.file.replace(/\.schema\.json$/, '')),
    `[\`templates/kinds/${s.file}\`](${blob(`templates/kinds/${s.file}`)})`,
    (s.json.required ?? []).length ? s.json.required.map(tick).join(', ') : '—',
  ]);
  out.push(`\n${mdx(table(t.kindsSchemaTable, schemaRows))}\n`);
  return out.join('');
}

function copyPage(title, desc, sourceRel, text, intro) {
  return [
    front(title, desc),
    callout,
    generatedBy(`[\`${sourceRel}\`](${blob(sourceRel)})`),
    intro ? `\n${mdx(intro)}\n` : '',
    `\n${mdx(relink(text, sourceRel)).trim()}\n`,
  ].join('');
}

