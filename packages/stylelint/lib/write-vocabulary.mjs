/** Regenerates `vocabulary.generated.mjs` and `grammar-values.generated.mjs` from the grammar package: `npm run vocabulary`. */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { extractValues } from "./extract-values.mjs"
import { extractVocabulary } from "./extract-vocabulary.mjs"

const here = path.dirname(fileURLToPath(import.meta.url))
const grammarSrc = path.resolve(here, "../../grammar/src")
const { declared, vendor, breakpoints, statusTones } = extractVocabulary(grammarSrc)
const list = (names) => names.map((name) => `  ${JSON.stringify(name)},`).join("\n")
fs.writeFileSync(
  path.join(here, "vocabulary.generated.mjs"),
  `// Generated by lib/write-vocabulary.mjs from packages/grammar/src. Do not edit: run \`npm run vocabulary\`.\n\n` +
    `/** Un-prefixed custom properties the grammar declares (and the soft pair of every status tone). */\nexport const DECLARED = [\n${list(declared)}\n]\n\n` +
    `/** Un-prefixed custom properties the grammar reads but a vendor layer declares. */\nexport const VENDOR = [\n${list(vendor)}\n]\n\n` +
    `/** Width breakpoints of the grammar's media queries, ascending. */\nexport const BREAKPOINTS = [\n${list(breakpoints)}\n]\n\n` +
    `/** The status tones: each has a solid pair and a soft pair, in light and in dark. */\nexport const STATUS_TONES = [\n${list(statusTones)}\n]\n`,
)
const values = extractValues(grammarSrc)
fs.writeFileSync(
  path.join(here, "grammar-values.generated.mjs"),
  `// Generated by lib/write-vocabulary.mjs from packages/grammar/src. Do not edit: run \`npm run vocabulary\`.\n\n` +
    `/** The custom properties the grammar declares on its theme roots, per theme and family (\`common\` is the root every family sits on). */\n` +
    `export const GRAMMAR_VALUES = ${JSON.stringify(values, null, 2)}\n`,
)
// eslint-fe judges class names against the same tone list, so it ships the one generated copy of it.
const feTones = path.resolve(here, "../../eslint/fe/lib/status-tones.generated.mjs")
fs.writeFileSync(
  feTones,
  `// Generated by packages/stylelint/lib/write-vocabulary.mjs from packages/grammar/src. Do not edit: run \`npm run vocabulary\` in packages/stylelint.\n\n` +
    `/** The status tones of the grammar: each has a solid pair and a soft pair (\`--<tone>-soft\`, \`--<tone>-soft-foreground\`). */\nexport const STATUS_TONES = [\n${list(statusTones)}\n]\n`,
)
console.log(`vocabulary.generated.mjs: ${declared.length} declared, ${vendor.length} vendor, ${breakpoints.length} breakpoints, ${statusTones.length} status tones; grammar-values.generated.mjs; eslint-fe status-tones.generated.mjs`)
