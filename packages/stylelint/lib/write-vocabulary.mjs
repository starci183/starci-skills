/** Regenerates `vocabulary.generated.mjs` from the grammar package: `npm run vocabulary`. */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { extractVocabulary } from "./extract-vocabulary.mjs"

const here = path.dirname(fileURLToPath(import.meta.url))
const { declared, vendor, breakpoints } = extractVocabulary(path.resolve(here, "../../grammar/src"))
const list = (names) => names.map((name) => `  ${JSON.stringify(name)},`).join("\n")
fs.writeFileSync(
  path.join(here, "vocabulary.generated.mjs"),
  `// Generated by lib/write-vocabulary.mjs from packages/grammar/src. Do not edit: run \`npm run vocabulary\`.\n\n` +
    `/** Un-prefixed custom properties the grammar declares. */\nexport const DECLARED = [\n${list(declared)}\n]\n\n` +
    `/** Un-prefixed custom properties the grammar reads but a vendor layer declares. */\nexport const VENDOR = [\n${list(vendor)}\n]\n\n` +
    `/** Width breakpoints of the grammar's media queries, ascending. */\nexport const BREAKPOINTS = [\n${list(breakpoints)}\n]\n`,
)
console.log(`vocabulary.generated.mjs: ${declared.length} declared, ${vendor.length} vendor, ${breakpoints.length} breakpoints`)
