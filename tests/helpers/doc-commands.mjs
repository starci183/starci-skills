import fs from 'node:fs';
import path from 'node:path';
import { validateArgs } from '../../packages/cli/src/validate-args.mjs';

// Finds every `starci <group> <verb> ...` the repository shows to an agent or owner and checks it the way the
// dispatcher would: group and verb exist, every flag is declared, enum values are valid, required flags and
// positionals are present unless the text is a fragment (a bare verb, a line that ends in an ellipsis, a flag
// mentioned on its own).

const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'coverage']);
const TEXT_EXT = ['.md', '.yaml', '.yml', '.json', '.txt', '.mjs', '.ts', '.tsx'];
const OUTSIDE = [/^modules\/cli\/commands\//, /^modules\/kernel\/contract-changes\//];

export const walk = (dir, ext) => {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (SKIP_DIRS.has(entry.name)) return [];
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full, ext);
    return ext.some((x) => entry.name.endsWith(x)) ? [full] : [];
  });
};

const rel = (root, file) => path.relative(root, file).split(path.sep).join('/');

/** Every file whose text tells somebody to run a starci command. */
export function docCommandFiles(root) {
  const files = [
    ...walk(path.join(root, 'docs'), ['.md']),
    ...walk(path.join(root, 'skills'), ['.md']),
    ...walk(path.join(root, 'modules'), ['.yaml', '.md']),
    ...walk(path.join(root, 'knowledge'), TEXT_EXT),
    ...walk(path.join(root, 'ui'), ['.md']),
    ...walk(path.join(root, 'scripts'), ['.mjs']),
    ...['README.md', 'CONTRIBUTING.md', 'CONTEXT.md', 'benchmark/README.md'].map((f) => path.join(root, f)),
  ];
  return files
    .filter((f) => fs.existsSync(f))
    .filter((f) => !OUTSIDE.some((re) => re.test(rel(root, f))))
    .filter((f) => !/(^|\/)CHANGELOG[^/]*\.md$/.test(rel(root, f)))
    .filter((f) => !/GENERATED by [\w./-]+ — do not edit/.test(fs.readFileSync(f, 'utf8').slice(0, 300)));
}

// ---- tokenising -----------------------------------------------------------------------------------------------

const CLOSERS = { '<': '>', '[': ']', '{': '}', '(': ')' };

// One shell-like atom: a run of non-space characters in which <...>, [...], {...}, (...) and quoted parts may hold spaces.
function readAtom(s, start) {
  let i = start;
  while (i < s.length && !/\s/.test(s[i])) {
    const c = s[i];
    if (c === '<' || c === '[' || c === '{' || c === '(') {
      let depth = 0;
      let j = i;
      for (; j < s.length; j += 1) {
        if (s[j] === c) depth += 1;
        else if (s[j] === CLOSERS[c] && (depth -= 1) === 0) break;
      }
      if (j >= s.length) return s.length;
      i = j + 1;
    } else if ((c === '"' || c === "'") && (i === start || s[i - 1] === '=')) {
      const j = s.indexOf(c, i + 1);
      i = j < 0 ? i + 1 : j + 1;
    } else i += 1;
  }
  return i;
}

const CUT = { text: '#', optional: false };
const PLACEHOLDER = /^<.*>$|^\$\{?[\w.]+\}?$|^\$\{.*\}$|^\{.*\}$|<[^>]+>|\$\{/;
const TRAILING = /[.,;:!?)'"`\]}]+$/;
const IDENTIFIER = /^[a-z][a-z0-9-]*$/;
// a sentence that quotes a command only to say it is gone is not an instruction to run it
const RETIRED_SENTENCE = /^[^.;]*?\b(?:is|was|are|were)\s+(?:now\s+)?(?:gone|removed|retired|dropped)\b/;

// Flat tokens of a command tail. [..] and (..) groups are optional text (all their alternatives are named); a (..) group
// that opens with a plain word is commentary and ends the command; a token that ends a sentence ends the command.
function tokenise(text, optional = false) {
  const tokens = [];
  let i = 0;
  while (i < text.length) {
    if (/\s/.test(text[i])) { i += 1; continue; }
    const end = readAtom(text, i);
    let atom = text.slice(i, end);
    i = end;
    const closed = atom.startsWith('[') ? atom.replace(/[.,;:)]+$/, '') : atom;
    const grouped = closed.length > 2 && ((closed.startsWith('[') && closed.endsWith(']')) || (closed.startsWith('(') && closed.endsWith(')')));
    if (grouped) {
      const body = closed.slice(1, -1);
      if (atom.startsWith('(') && !/^\s*(--|<|\[|\$)/.test(body)) { tokens.push(CUT); break; }
      tokens.push(...tokenise(body, true).filter((t) => t.text !== '|'));
      if (closed !== atom && /[.,;:]/.test(atom.slice(closed.length))) break;
      continue;
    }
    if (atom.length > 1 && /^(['"]).*\1$/.test(atom)) atom = atom.slice(1, -1);
    const tail = /^\.{1,2}$/.test(atom) ? null : TRAILING.exec(atom);
    const bare = tail && !PLACEHOLDER.test(atom) ? atom.slice(0, tail.index) : atom;
    if (bare) tokens.push({ text: bare, optional });
    if (tail && !PLACEHOLDER.test(atom) && /[^\]]/.test(tail[0])) break;
  }
  return tokens;
}

const isPlaceholder = (t) => PLACEHOLDER.test(t);
// a flag family (`--until-*`, `--until-<type>`, `--until-...`) names no single flag
const isEllipsis = (t) => t === '...' || t === '…' || /\.\.\.$/.test(t) || /^--[\w-]*(-\*|-<[^>]*>|-)$/.test(t) || /^[<[]?(options?|flags?|args?|arguments?|rest|more|etc)[>\]]?$/i.test(t);
const SEPARATORS = new Set(['|', '||', '&&', ';', '>', '>>', '<', '&', '2>', '2>&1', '#', '\\', 'then', 'do', '-', '—', '–', '→', '←', '=>', '->', '-->', '=', '+', '/', 'and', 'or', 'to']);
const alternatives = (t) => (!/[<{$]/.test(t) && (t.includes('|') || (/^[a-z]/.test(t) && t.includes('/'))) ? t.split(/[|/]/) : [t]);
const inner = (t) => t.replace(/^<|>$/g, '');

// ---- extraction -----------------------------------------------------------------------------------------------

const STARCI_AT = /(?<![\w@./:-])(?:npx\s+starci|npm\s+run\s+starci(?:\s+--silent)?(?:\s+--)?|starci)(?![\w@./-])(?=\s|$)/g;

const COMMAND_POSITION = /^(?:\s*(?:[$>]|PS>)?\s*(?:[A-Za-z_]+=\S*\s+)*|.*(?:&&|\|\||;|\||\(|\bthen|\bdo|\bsudo|\bexec)\s*)$/;

function spansOf(line) {
  const spans = [];
  const masked = line.replace(/(`+)((?:(?!\1).)+?)\1/g, (m, _t, body) => {
    spans.push(body);
    return ' '.repeat(m.length);
  });
  return { spans, masked };
}

// Escapes of the host language (JSON/YAML/JS string literals) are not part of the command.
const unescape = (s) => s.replace(/\\[nt]/g, ' ').replace(/\\(["'`])/g, '$1').replace(/\\$/, '');

/**
 * Every starci command occurrence in one text.
 * `bounded` occurrences (inside a code span, a fenced line, or a script string literal span) run to the end of that
 * span; `prose` occurrences inside running text only keep the flags and values that follow the verb.
 */
export function extractCommands(text, { kind = 'text' } = {}) {
  const found = [];
  let fenced = false;
  const lines = text.split(/\r?\n/);
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const lineNo = index + 1;
    const add = (body, mode) => {
      for (const m of body.matchAll(STARCI_AT)) {
        found.push({ line: lineNo, mode, preceded: body.slice(0, m.index), text: unescape(body.slice(m.index + m[0].length)) });
      }
    };
    if (kind !== 'script' && /^\s*(?:[-*>|]\s*)?```/.test(line)) { fenced = !fenced; continue; }
    if (fenced) {
      let code = line;
      while (/\\\s*$/.test(code) && index + 1 < lines.length && !/^\s*```/.test(lines[index + 1])) {
        index += 1;
        code = `${code.replace(/\\\s*$/, ' ')}${lines[index]}`;
      }
      // a fenced line is a command where starci stands in command position; elsewhere it is a diagram or a sentence
      for (const m of code.replace(/\s+#\s.*$/, '').matchAll(STARCI_AT)) {
        const before = code.slice(0, m.index);
        const mode = COMMAND_POSITION.test(before) ? 'bounded' : 'prose';
        found.push({ line: lineNo, mode, preceded: before, text: unescape(code.slice(m.index + m[0].length)) });
      }
      continue;
    }
    const segments = kind === 'script'
      // a literal in a `spelling:` field is a retired command kept so the dispatcher can refuse it
      ? [...line.matchAll(/(['"`])((?:\\.|(?!\1).)*)\1/g)].filter((m) => !/\bspelling:\s*$/.test(line.slice(0, m.index))).map((m) => m[2])
      : [line];
    for (const segment of segments) {
      const { spans, masked } = spansOf(segment);
      for (const span of spans) add(span, 'bounded');
      add(masked, 'prose');
    }
  }
  return found;
}

// ---- validation -----------------------------------------------------------------------------------------------

const sampleFor = (flag) => {
  if (flag.type === 'enum') return flag.enum[0];
  if (flag.type === 'number') return '1';
  if (flag.type === 'boolean') return 'true';
  return 'x';
};

const GLOBAL_BEFORE = (tokens, globals) => {
  let i = 0;
  while (i < tokens.length && tokens[i].text.startsWith('--')) {
    const g = globals.get(tokens[i].text.slice(2).split('=')[0]);
    if (!g) break;
    i += g.type === 'boolean' || tokens[i].text.includes('=') ? 1 : 2;
  }
  return i;
};

/** Returns [] when the command is a valid call (or a fragment of one), else the reasons it is not. */
export function checkCommand(occurrence, catalog) {
  const errors = [];
  const bounded = occurrence.mode === 'bounded';
  if (RETIRED_SENTENCE.test(occurrence.text)) return errors;
  let tokens = tokenise(occurrence.text.split(/\s{3,}/)[0].trim());
  const cut = tokens.findIndex((t) => SEPARATORS.has(t.text) || /^\d?>/.test(t.text) || t.text === 'starci');
  if (cut >= 0) tokens = tokens.slice(0, cut);

  const globals = new Map(catalog.global.map((f) => [f.name, f]));
  const i = GLOBAL_BEFORE(tokens, globals);
  const head = tokens[i];
  if (!head) return errors;
  if (['help', '--help', '-h', '--version', 'completion'].includes(head.text) || isPlaceholder(head.text) || isEllipsis(head.text)) return errors;
  const groupAlts = alternatives(head.text);
  // `starci src/components/x`, `starci history guard: refused ...`: a path or a log label names no command
  if (!groupAlts.every((g) => IDENTIFIER.test(g))) return errors;
  if (!groupAlts.every((g) => catalog.groups[g]) && /^[\w-]+(?:\s+[\w-]+)?:(?:\s|$)/.test(occurrence.text.trim())) return errors;
  const asked = /\b(?:run|Run|execute|Execute)\s*$/.test(occurrence.preceded) || /^\s*(?:[-*>$]\s*)*$/.test(occurrence.preceded);
  if (!bounded && !asked && !groupAlts.every((g) => catalog.groups[g])) return errors;
  for (const g of groupAlts) if (!catalog.groups[g]) errors.push(`unknown group "${g}"`);
  if (errors.length) return errors;
  const group = catalog.groups[groupAlts[0]];

  const verbToken = tokens[i + 1];
  if (!verbToken || verbToken.text.startsWith('-') || isPlaceholder(verbToken.text) || isEllipsis(verbToken.text)) return errors;
  const verbAlts = alternatives(verbToken.text);
  if (!bounded && !asked && !verbAlts.some((v) => group.verbs[v])) return errors;
  for (const v of verbAlts) if (!group.verbs[v]) errors.push(`unknown verb "${groupAlts[0]} ${v}"`);
  if (errors.length) return errors;
  const rest = tokens.slice(i + 2);

  if (verbAlts.length > 1 || groupAlts.length > 1) {
    // alternatives of groups or verbs: only existence and the flag names are provable
    for (const t of rest) {
      if (!t.text.startsWith('--')) continue;
      for (const n of alternatives(t.text).map((a) => a.replace(/^--/, '').split('=')[0])) {
        const some = verbAlts.some((v) => group.verbs[v].flags?.some((f) => f.name === n)) || globals.has(n);
        if (!some) errors.push(`--${n} is not a flag of ${groupAlts[0]} ${verbAlts.join('|')}`);
      }
    }
    return errors;
  }

  const verbName = verbAlts[0];
  const verb = { ...group.verbs[verbName], group: groupAlts[0], verb: verbName };
  const declared = new Map([...catalog.global, ...(verb.flags ?? [])].map((f) => [f.name, f]));
  const schema = verb.positional ?? [];
  const argv = [];
  let fragment = rest.length === 0;
  let valued = false;
  let position = 0;

  for (let k = 0; k < rest.length; k += 1) {
    const t = rest[k];
    if (isEllipsis(t.text)) { fragment = true; if (!bounded) break; continue; }
    if (t.text === '--') { fragment = true; break; }
    if (t.text.startsWith('--')) {
      const alts = alternatives(t.text).map((a) => a.replace(/^--/, ''));
      const eq = alts[0].indexOf('=');
      const name = eq >= 0 ? alts[0].slice(0, eq) : alts[0];
      let value = eq >= 0 ? alts[0].slice(eq + 1) : undefined;
      let bad = false;
      for (const a of alts) {
        const an = a.split('=')[0];
        if (!declared.has(an)) { errors.push(`unknown option --${an}`); bad = true; }
      }
      if (bad) continue;
      const flag = declared.get(name);
      if (flag.type === 'boolean') { argv.push(`--${name}`); continue; }
      if (value === undefined) {
        const next = rest[k + 1];
        if (next && !next.text.startsWith('--') && !isEllipsis(next.text)) { value = next.text; k += 1; }
        else value = null;
      }
      if (value !== null) valued = true;
      const literal = value === null || isPlaceholder(value) ? null : value;
      if (flag.type === 'enum') {
        const choices = literal !== null ? alternatives(literal) : value !== null && /^<.+\|.+>$/.test(value) ? inner(value).split('|') : [];
        for (const c of choices) if (/^[\w-]+$/.test(c) && !flag.enum.includes(c)) errors.push(`--${name} expects one of: ${flag.enum.join(', ')} (got ${c})`);
        argv.push(`--${name}`, flag.enum[0]);
      } else if (flag.type === 'number' || literal === null) argv.push(`--${name}`, sampleFor(flag));
      else argv.push(`--${name}`, literal);
      continue;
    }
    if (!bounded && !/^<.*>$/.test(t.text)) break;
    if (t.text.startsWith('-') && t.text.length > 1) { errors.push(`unknown option ${t.text}`); continue; }
    const entry = schema[Math.min(position, schema.length - 1)];
    position += 1;
    valued = true;
    const alts = /^<.+\|.+>$/.test(t.text) ? inner(t.text).split('|') : null;
    if (entry?.enum && alts) {
      for (const c of alts) if (/^[\w-]+$/.test(c) && !entry.enum.includes(c)) errors.push(`${entry.name} expects one of: ${entry.enum.join(', ')} (got ${c})`);
      argv.push(entry.enum[0]);
    } else if (isPlaceholder(t.text) || t.text.includes('|')) argv.push(entry?.enum ? entry.enum[0] : 'x');
    else argv.push(t.text);
  }
  if (errors.length) return errors;

  // A mention that is not a whole call (prose, no value given, an ellipsis) is only held to the flags it names.
  const whole = bounded && valued && !fragment;
  for (let attempt = 0; attempt < 30; attempt += 1) {
    const result = validateArgs(argv, verb, catalog.global);
    if (result.ok) return errors;
    const missingFlag = /^missing required option --(.+)$/.exec(result.error);
    const missingPositional = /^missing required positional (.+)$/.exec(result.error);
    if (missingFlag && !whole) { argv.push(`--${missingFlag[1]}`, sampleFor(declared.get(missingFlag[1]))); continue; }
    if (missingPositional && !whole) { argv.push(schema.find((s) => s.name === missingPositional[1])?.enum?.[0] ?? 'x'); continue; }
    errors.push(result.error);
    return errors;
  }
  return errors;
}

/** All problems of one file as `file:line command -> reason`. */
export function problemsIn(root, file, catalog) {
  const name = rel(root, file);
  const text = fs.readFileSync(file, 'utf8');
  if (!text.includes('starci')) return [];
  const kind = file.endsWith('.mjs') ? 'script' : 'text';
  const problems = [];
  for (const occurrence of extractCommands(text, { kind })) {
    for (const reason of checkCommand(occurrence, catalog)) {
      problems.push(`${name}:${occurrence.line} starci ${occurrence.text.trim().slice(0, 90)} -> ${reason}`);
    }
  }
  return problems;
}
