import fs from 'node:fs';
import path from 'node:path';
import { extractCommands, checkCommand } from '../../scripts/checks/lib/doc-commands.mjs';

// Finds every `starci <group> <verb> ...` the repository shows to an agent or owner and checks it the way the
// dispatcher would: group and verb exist, every flag is declared, enum values are valid, required flags and
// positionals are present unless the text is a fragment (a bare verb, a line that ends in an ellipsis, a flag
// mentioned on its own).

const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'coverage']);
const TEXT_EXT = ['.md', '.yaml', '.yml', '.json', '.txt', '.mjs', '.ts', '.tsx'];
const OUTSIDE = [/^modules\/cli\/commands\//];

export const walk = (dir, ext) => {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (SKIP_DIRS.has(entry.name)) return [];
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full, ext);
    return ext.some((x) => entry.name.endsWith(x)) ? [full] : [];
  });
};

const rel = (root, file) => path.relative(root, file).split(path.sep).join('/');

/** Every file whose text tells somebody to run a starci command. */
export function docCommandFiles(root) {
  const files = [
    ...walk(path.join(root, 'docs'), ['.md']),
    ...walk(path.join(root, 'skills'), ['.md']),
    ...walk(path.join(root, 'modules'), ['.yaml', '.md']),
    ...walk(path.join(root, 'knowledge'), TEXT_EXT),
    ...walk(path.join(root, 'ui'), ['.md']),
    ...walk(path.join(root, 'scripts'), ['.mjs']),
    ...['README.md', 'CONTRIBUTING.md', 'CONTEXT.md', 'benchmark/README.md'].map((f) => path.join(root, f)),
  ];
  return files
    .filter((f) => fs.existsSync(f))
    .filter((f) => !OUTSIDE.some((re) => re.test(rel(root, f))))
    .filter((f) => !/(^|\/)CHANGELOG[^/]*\.md$/.test(rel(root, f)))
    .filter((f) => !/GENERATED by [\w./-]+ — do not edit/.test(fs.readFileSync(f, 'utf8').slice(0, 300)));
}

/** All problems of one file as `file:line command -> reason`. */
export function problemsIn(root, file, catalog) {
  const name = rel(root, file);
  const text = fs.readFileSync(file, 'utf8');
  if (!text.includes('starci')) return [];
  const kind = file.endsWith('.mjs') ? 'script' : 'text';
  const problems = [];
  for (const occurrence of extractCommands(text, { kind })) {
    for (const reason of checkCommand(occurrence, catalog)) {
      problems.push(`${name}:${occurrence.line} starci ${occurrence.text.trim().slice(0, 90)} -> ${reason}`);
    }
  }
  return problems;
}
