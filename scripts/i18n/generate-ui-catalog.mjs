#!/usr/bin/env node
// generate-ui-catalog.mjs - render the browser-readable TypeScript map from the one YAML catalog source.
// The output is ignored and disposable; `ui` build and dev scripts regenerate it before Vite or TypeScript starts.
import fs from 'node:fs';
import path from 'node:path';
import { skillRoot } from '../../engine/runtime-root.mjs';
import { catalogEntries } from '../lib/i18n.mjs';
import { isMain } from '../lib/is-main.mjs';

const UI_CATALOG_FILE = 'ui/src/i18n/generated/catalog.ts';

function uiCatalogSource(root = skillRoot) {
  const entries = catalogEntries(root, { scope: 'ui' });
  const catalog = Object.fromEntries(entries.map(({ en, vi }) => [en, vi]));
  if (Object.keys(catalog).length !== entries.length) throw new Error('The UI i18n scope contains duplicate English sources');
  return [
    '// Generated by scripts/i18n/generate-ui-catalog.mjs from modules/i18n/messages/ui.yaml.',
    '// Do not edit or commit this file.',
    `export default ${JSON.stringify(catalog, null, 2)} as Record<string, string>;`,
    '',
  ].join('\n');
}

function generateUiCatalog(root = skillRoot) {
  const target = path.join(root, ...UI_CATALOG_FILE.split('/'));
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, uiCatalogSource(root), 'utf8');
  return { target, entries: catalogEntries(root, { scope: 'ui' }).length };
}

if (isMain(import.meta.url)) {
  const result = generateUiCatalog();
  console.log(`Generated ${result.entries} UI translations at ${UI_CATALOG_FILE}.`);
}
