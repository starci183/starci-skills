// runtime-coverage-scope.mjs - THE list of what the runtime measures and analyses in its own tag-run CI (the `runtime` Codecov flag and
// the root Sonar project). One input, three consumers, nothing typed twice:
//   - the coverage producer (scripts/gates/runtime-coverage.mjs): `runtimeCoverageNodeArgs` are the node:test coverage include and exclude
//     globs of `npm run test:coverage`, so the lcov denominator is this source and not the specs or node_modules;
//   - Codecov: `runtimeCodecovPaths` are the paths of the `runtime` flag, rendered into codecov.yml by scripts/checks/check-examples-ci.mjs;
//   - SonarCloud: `renderRuntimeSonar` is the root sonar-project.properties, rendered by the same generator (sources, tests, exclusions and the
//     lcov report path from `coverage/lcov.info`). It names neither organization nor project key: those are the repository variables
//     SONAR_ORGANIZATION and SONAR_PROJECT_KEY, passed as -D arguments by .github/workflows/ci.yml.
// The examples keep their own flags and Sonar projects (scripts/hfs/coverage-scope.mjs); packages/*/runtime/ copies, examples/ and
// the vendored engine/yaml.mjs bundle are never in this scope. Pure: no imports, no filesystem.

/** The Codecov flag of the runtime. */
export const RUNTIME_FLAG = 'runtime';
const RUNTIME_SONAR_NAME = 'StarCi runtime';
/** The lcov file the coverage producer writes and Codecov and Sonar read, from the repository root. */
export const RUNTIME_LCOV = 'coverage/lcov.info';
/** The test entry the coverage run replaces `npm test` with: the same glob, the same isolation preloads. */
export const RUNTIME_TEST_GLOB = 'tests/**/*.spec.mjs';

/** The first-party source: directories and single files, repository-relative POSIX. */
const RUNTIME_SOURCES = Object.freeze(['engine', 'scripts', 'packages/cli', 'ui/api', 'ui/harness-process.mjs', 'ui/harness-verbs.mjs', 'ui/ports.mjs', 'ui/server.mjs']);
/** Inside the sources, never measured or analysed: the vendored yaml bundle (generated, frozen), dependencies and specs. */
const RUNTIME_EXCLUDES = Object.freeze(['engine/yaml.mjs', '**/node_modules/**', '**/*.spec.mjs']);
/** The roots of the specs Sonar classifies as tests. */
const RUNTIME_TEST_ROOTS = Object.freeze(['tests', 'packages/cli/src']);
/** Never analysed whatever the sources say: examples keep their own projects, generated copies and build output are not authored. */
const RUNTIME_SONAR_ONLY_EXCLUDES = Object.freeze(['examples/**', 'packages/*/runtime/**', 'packages/*/*/runtime/**', 'ui/dist/**', '**/dist/**', 'coverage/**']);

const isFile = (entry) => /\.m?[jt]s$/.test(entry);
/** The glob of a source entry: a directory is `<dir>/**`, a file is itself. */
const globOf = (entry) => (isFile(entry) ? entry : `${entry}/**`);

/** The paths of the Codecov `runtime` flag. */
export const runtimeCodecovPaths = () => RUNTIME_SOURCES.map(globOf);

/** The node:test coverage options of the coverage run: include the sources, exclude the bundle, dependencies and specs. */
export const runtimeCoverageNodeArgs = () => [
  '--experimental-test-coverage',
  ...runtimeCodecovPaths().map((glob) => `--test-coverage-include=${glob}`),
  ...RUNTIME_EXCLUDES.map((glob) => `--test-coverage-exclude=${glob}`),
];

/** The root sonar-project.properties of the runtime (LF, trailing newline). */
export const renderRuntimeSonar = () => `# Generated by scripts/checks/check-examples-ci.mjs --write from scripts/hfs/runtime-coverage-scope.mjs. Do not edit: npm run check fails on any difference.
# The runtime's own SonarCloud project: its first-party source, analysed with the lcov of \`npm run test:coverage\` (coverage/lcov.info).
# sonar.organization and sonar.projectKey are not here: .github/workflows/ci.yml passes them from the repository variables SONAR_ORGANIZATION and SONAR_PROJECT_KEY.
sonar.projectName=${RUNTIME_SONAR_NAME}
sonar.sourceEncoding=UTF-8
sonar.sources=${RUNTIME_SOURCES.join(',')}
sonar.tests=${RUNTIME_TEST_ROOTS.join(',')}
sonar.test.inclusions=**/*.spec.mjs
sonar.test.exclusions=**/node_modules/**
sonar.exclusions=${[...RUNTIME_EXCLUDES, ...RUNTIME_SONAR_ONLY_EXCLUDES].join(',')}
sonar.javascript.lcov.reportPaths=${RUNTIME_LCOV}
sonar.nodejs.maxspace=8192
`;
