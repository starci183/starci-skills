import fs from "node:fs"
import path from "node:path"

/**
 * Turns the GraphQL documents of one app into the typed table the transport client sends.
 *
 * Documents live in `.graphql` files next to the module that owns the call; this script reads every
 * one of them under the app's `src/`, keys each by its operation name and writes the table to the
 * output path it is given (default `src/modules/api/__generated__/documents.ts`; ignored by git, rebuilt
 * by `codegen` before build, typecheck and lint). Run from the app directory:
 * `node ../../scripts/codegen-documents.mjs [output]`.
 */

const SOURCE_ROOT = path.resolve(process.cwd(), "src")
const OUTPUT = path.resolve(process.cwd(), process.argv[2] ?? "src/modules/api/__generated__/documents.ts")
const OPERATION = /^\s*(?:query|mutation)\s+([A-Za-z_][A-Za-z0-9_]*)/m

/** Every `.graphql` file under a directory, in a stable order. */
const documentFiles = (directory) =>
    fs
        .readdirSync(directory, { withFileTypes: true })
        .flatMap((entry) => {
            const full = path.join(directory, entry.name)
            if (entry.isDirectory()) return entry.name === "__generated__" ? [] : documentFiles(full)
            return entry.name.endsWith(".graphql") ? [full] : []
        })
        .sort()

const documents = new Map()
for (const file of documentFiles(SOURCE_ROOT)) {
    const text = fs.readFileSync(file, "utf8").trim()
    const match = OPERATION.exec(text)
    if (match === null) throw new Error(`${path.relative(SOURCE_ROOT, file)} names no query or mutation`)
    if (documents.has(match[1])) throw new Error(`operation ${match[1]} is declared twice`)
    documents.set(match[1], text.replace(/\s+/g, " "))
}

const body = [...documents].map(([name, text]) => `    ${name}: ${JSON.stringify(text)},`).join("\n")
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
fs.writeFileSync(
    OUTPUT,
    `/** Generated by codegen from the \`.graphql\` documents; never edited by hand. */\nexport const DOCUMENTS = {\n${body}\n} as const\n\n/** The operations the client can send. */\nexport type OperationName = keyof typeof DOCUMENTS\n`,
)
